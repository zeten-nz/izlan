/** Fail closed: forbidden in production, requires ALLOW_DEV_FIXTURE=true and the (reused) demo passwords (policy-valid). */
export function assertRuntimeFixtureAllowed(env: RuntimeFixtureEnv): { adminPassword: string; learnerPassword: string } {
  if ((env.nodeEnv ?? '').trim() === 'production') throw new Error('db:seed:runtime is forbidden in production');
  if ((env.allowDevFixture ?? '').trim() !== 'true') throw new Error('db:seed:runtime requires ALLOW_DEV_FIXTURE=true');
  if (!env.adminPassword || !env.learnerPassword) {
    throw new Error('DEMO_ADMIN_PASSWORD and DEMO_LEARNER_PASSWORD are required');
  }
  assertPasswordPolicy(env.adminPassword);
  assertPasswordPolicy(env.learnerPassword);
  return { adminPassword: env.adminPassword, learnerPassword: env.learnerPassword };
}

